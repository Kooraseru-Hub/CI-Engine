"use strict";
const fs=require("node:fs"),path=require("node:path");
const MARKER="          # Engine-generated environment bindings (direct workflow only)";
const PIN=/^[\w.-]+\/[\w.-]+$/;
const SHA=/^[a-f0-9]{40}$/;
const NAME=/^[A-Za-z][A-Za-z0-9_]{0,63}$/;
const ENV=/^[A-Za-z][A-Za-z0-9_-]{0,63}$/;
function bindingLines(environments={}){
  const sources=new Map();
  for(const [environment,bindings] of Object.entries(environments)){
    if(!ENV.test(environment)||!bindings||typeof bindings!=="object"||Array.isArray(bindings))throw Error("Invalid credential environment");
    for(const alias of Object.values(bindings)){
      const match=typeof alias==="string"&&/^(secrets|vars)\.([A-Za-z][A-Za-z0-9_]{0,63})$/.exec(alias);
      if(!match)throw Error("Invalid environment credential reference");
      const source=match[1]==="secrets"?"secret":"variable",name=match[2].toUpperCase();
      if(!NAME.test(name)||name.startsWith("GITHUB_"))throw Error("Invalid credential name");
      const key="CI_BIND_"+source.toUpperCase()+"_"+name;
      if(!sources.has(key))sources.set(key,{source,name,context:match[1],environments:new Set()});
      sources.get(key).environments.add(environment);
    }
  }
  return [...sources.entries()].sort(([a],[b])=>a.localeCompare(b)).map(([key,b])=>{
    const allowed=[...b.environments].sort().map(e=>"matrix.environment == '"+e+"'").join(" || ");
    return "          "+key+": ${{ ("+allowed+") && contains(matrix."+b.source+"_names, '"+b.name+"') && "+b.context+"."+b.name+" || '' }}";
  });
}
function renderWorkflow(template,revision,environments={}){
  if(!revision||!PIN.test(revision.repository||"")||!SHA.test(revision.sha||"")||revision.workflow!=="bootstrap.yml")throw Error("Expected a pinned CI Engine revision");
  const pin=revision.repository+"@"+revision.sha;
  if(!/^name: CI Engine\non:/m.test(template)&&!/^name: CI Engine\n\non:/m.test(template))throw Error("Invalid CI Engine workflow template");
  const start=template.indexOf("\non:"),end=template.indexOf("\njobs:");
  if(start<0||end<=start)throw Error("Missing CI Engine workflow header");
  const lines=bindingLines(environments);
  let result=template.slice(0,start)+"\n\non:\n  repository_dispatch:\n    types: [ci-request]\n\npermissions: {}\n"+template.slice(end);
  const markers=result.split(MARKER).length-1;
  if(markers!==5)throw Error("Unexpected CI Engine delivery binding marker count");
  result=result.replaceAll(MARKER,lines.join("\n"))
    .replaceAll("uses: $/","uses: "+pin)
    .replaceAll("inputs.request","toJSON(github.event.client_payload)")
    .replaceAll("inputs.operation","github.event.client_payload.operation")
    .replaceAll("inputs.publish","github.event.client_payload.publish");
  if(result.includes("inputs.")||result.includes("uses: $/"))throw Error("Unresolved CI Engine workflow template reference");
  return "# Generated by CI Engine sync-workflow; do not edit.\n# Engine: "+pin+"\n"+result;
}
function syncWorkflow(root,packageRoot,check=false){
  const revision=JSON.parse(fs.readFileSync(path.join(packageRoot,".dependency-revision.json"),"utf8"));
  const template=fs.readFileSync(path.join(packageRoot,".github/workflows/bootstrap.yml"),"utf8");
  const catalogFile=path.join(root,"config/credentials.json");
  const catalog=fs.existsSync(catalogFile)?require("../../native/github/authentication/catalog.cjs").load(catalogFile):{};
  const generated=renderWorkflow(template,revision,catalog.environments);
  const destination=path.join(root,".github/workflows/bootstrap.yml");
  const current=fs.existsSync(destination)?fs.readFileSync(destination,"utf8"):"";
  if(current===generated)return false;
  if(check)throw Error("Generated CI workflow is stale; run CI Engine sync-workflow");
  fs.writeFileSync(destination,generated);
  return true;
}
module.exports={bindingLines,renderWorkflow,syncWorkflow};
